export const DICTS: Record<Lang, Dict> = { en, te, hi };

/** Translate a key with optional {placeholder} interpolation. */
export function tr(
  key: string,
  vars?: Record<string, string | number>,
  lang: Lang = getLang(),
): string {
  const raw = DICTS[lang]?.[key] ?? DICTS.en[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_m, k: string) =>
    vars[k] === undefined ? `{${k}}` : String(vars[k]),
  );
}

/**
 * React hook: gives the current language plus a `t()` translator, and
 * re-renders the component whenever the global language changes (voice
 * command, settings toggle, or header buttons).
 */
export function useT() {
  const [lang, setLangState] = useState<Lang>(() => getLang());

  useEffect(() => {
    setLangState(getLang()); // sync after hydration (localStorage)
    return onLangChange(setLangState);
  }, []);

  return {
    lang,
    t: (key: string, vars?: Record<string, string | number>) => tr(key, vars, lang),
    setLang,
    langLabel: LANG_LABEL,
  };
}
